def distance_city(city_1, city_2) -> float:
    """Calculate distance to another city using Haversine formula"""
    # Haversine formula for great-circle distance
    # REF_PI = 3.141592  # PI
    REF_EARTH_RADIUS = 6378.388  # Earth's radius in kilometers
    
    lon1_rad = math.radians(city_1[1])
    lon2_rad = math.radians(city_2[1])
    lat1_rad = math.radians(city_1[2])
    lat2_rad = math.radians(city_2[2])

    q1 = np.cos(lon1_rad - lon2_rad)
    q2 = np.cos(lat1_rad - lat2_rad)
    q3 = np.cos(lat1_rad + lat2_rad)

    distance = REF_EARTH_RADIUS * np.arccos(0.5 * ((1.0 + q1) * q2 -
                                                    (1.0 - q1) * q3)) + 1.0
    # Ensure the diagonal (distance between the same nodes) is 0
    return distance


class RealWorldTSPProblem:
    """TSP Problem using real-world city data"""

    def __init__(self,
                 problem_type: ProblemType,
                 cities,
                 n_salesmen: int = 1,
                 depots: Optional[List[int]] = None):
        self.problem_type = problem_type
        self.cities = cities
        self.n_nodes = len(cities)
        self.n_salesmen = n_salesmen
        self.depots = depots or [0] * n_salesmen
        # Create city lookup dictionary for O(1) access
        self.city_lookup = {city[0]: city for city in cities}
        self.distance_matrix = self._calculate_distance_matrix()

    def _calculate_distance_matrix(self) -> List[List[float]]:
        """Calculate distance matrix between all cities"""
        n = len(self.cities)
        print(f"matrix is {n}X{n}")
        print(f"cities are {self.cities[0]}")
        distance_matrix = [[0.0 for _ in range(n)] for _ in range(n)]

        # Only calculate upper triangle, then mirror for efficiency
        for i in range(n):
            for j in range(i + 1, n):
                distance = distance_city(self.cities[i], self.cities[j])
                distance_matrix[i][j] = distance
                distance_matrix[j][i] = distance  # Symmetric matrix
        return distance_matrix

    def get_info(self) -> dict:
        """Get problem information"""
        return {
            "Problem Type":
            self.problem_type.value,
            "Number of Cities":
            self.n_nodes,
            "Number of Salesmen":
            self.n_salesmen,
            "Depots":
            self.depots,
            # "City Range":
            # f"({min(c.longitude for c in self.cities):.2f}, {min(c.latitude for c in self.cities):.2f}) to ({max(c.longitude for c in self.cities):.2f}, {max(c.latitude for c in self.cities):.2f})"
        }

    def get_random_cities(self, n: int):
        """Get n random cities from the dataset"""
        if n > self.n_nodes:
            n = self.n_nodes
        return random.sample(self.cities, n)

    def display_city_numbers(self, cities):
        """Display city numbers and their coordinates"""
        cities_id = [city[0] for city in cities]
        print(f"Selected {len(cities)} random cities: {cities_id}")

    def get_city_by_number(self, city_number: int):
        """Get a specific city by its number in the dataset"""
        return self.city_lookup.get(city_number)

    def save_to_file(self, filename: str, solution: Union[List[int],
                                                          List[List[int]]],
                     total_cost: float) -> None:
        """Save TSP problem and solution to a text file"""
        with open(filename, 'w', encoding='utf-8') as f:
            f.write("=== TSP Problem Results ===\n\n")

            # Problem information
            f.write("PROBLEM INFORMATION:\n")
            f.write(f"Problem Type: {self.problem_type.value}\n")
            f.write(f"Number of Cities: {self.n_nodes}\n")
            f.write(f"Number of Salesmen: {self.n_salesmen}\n")
            f.write(f"Depots: {self.depots}\n")

            # City coordinates
            f.write(f"\nCITY COORDINATES:\n")
            for city in self.cities:
                f.write(
                    f"City {city[0]}: ({city[1]:.6f}, {city[2]:.6f})\n"
                )

            # Solution
            f.write(f"\nSOLUTION:\n")
            f.write(f"Total Distance: {total_cost:.2f} km\n")

            if isinstance(solution, list) and len(solution) > 0 and isinstance(
                    solution[0], list):
                # Multi-salesman solution
                f.write(f"Number of Routes: {len(solution)}\n")
                for i, route in enumerate(solution):
                    f.write(
                        f"Salesman {i+1} Route: {' -> '.join(map(str, route))}\n"
                    )
            else:
                # Single route solution
                f.write(f"Route: {' -> '.join(map(str, solution))}\n")


class RealWorldTSPSolver:
    """TSP Solver for real-world problems"""

    def solve(
            self,
            problem: RealWorldTSPProblem) -> Union[List[int], List[List[int]]]:
        """Solve TSP problem"""
        if problem.problem_type == ProblemType.MULTI_TSP:
            return self._solve_multi_tsp(problem)
        else:
            return self._solve_single_tsp(problem)

    def _solve_single_tsp(self, problem: RealWorldTSPProblem) -> List[int]:
        """Solve single TSP using nearest neighbor"""
        n = problem.n_nodes
        visited = [False] * n
        route = []

        # Start from city 0
        current_city = 0
        route.append(current_city)
        visited[current_city] = True

        # Visit remaining cities
        for _ in range(n - 1):
            nearest_distance = float('inf')
            nearest_city = None

            for j in range(n):
                if not visited[j] and problem.distance_matrix[current_city][
                        j] < nearest_distance:
                    nearest_distance = problem.distance_matrix[current_city][j]
                    nearest_city = j

            if nearest_city is not None:
                route.append(nearest_city)
                visited[nearest_city] = True
                current_city = nearest_city

        # Return to start
        route.append(route[0])
        return route

    def _solve_multi_tsp(self,
                         problem: RealWorldTSPProblem) -> List[List[int]]:
        """Solve multi-salesman TSP using greedy assignment"""
        n = problem.n_nodes
        n_salesmen = problem.n_salesmen
        depots = problem.depots

        # Initialize routes
        routes = [[] for _ in range(n_salesmen)]
        visited = [False] * n

        # Start each salesman at their depot
        for i, depot in enumerate(depots):
            routes[i].append(depot)
            visited[depot] = True

        # Assign remaining cities greedily
        remaining_cities = [i for i in range(n) if not visited[i]]

        while remaining_cities:
            best_assignment = None
            best_cost = float('inf')

            for city in remaining_cities:
                for salesman_idx in range(n_salesmen):
                    # Calculate cost of adding this city to this salesman's route
                    current_route = routes[salesman_idx]
                    if len(current_route) == 0:
                        cost = 0
                    else:
                        cost = problem.distance_matrix[current_route[-1]][city]

                    if cost < best_cost:
                        best_cost = cost
                        best_assignment = (city, salesman_idx)

            if best_assignment:
                city, salesman_idx = best_assignment
                routes[salesman_idx].append(city)
                visited[city] = True
                remaining_cities.remove(city)
            else:
                # Assign to first available salesman
                if remaining_cities:
                    city = remaining_cities.pop(0)
                    routes[0].append(city)
                    visited[city] = True

        # Complete routes by returning to depots
        for i, route in enumerate(routes):
            if len(route) > 0:
                route.append(route[0])

        return routes


def calculate_solution_cost(
        problem: RealWorldTSPProblem,
        solution: Union[List[int], List[List[int]]]) -> float:
    """Calculate the total distance of a solution"""
    if isinstance(solution, list) and len(solution) > 0 and isinstance(
            solution[0], list):
        # Multi-salesman solution
        total_cost = 0.0
        for route in solution:
            if len(route) > 1:
                for i in range(len(route) - 1):
                    total_cost += problem.distance_matrix[route[i]][route[i +
                                                                          1]]
        return total_cost
    else:
        # Single route solution
        if len(solution) <= 1:
            return 0.0

        total_cost = 0.0
        for i in range(len(solution) - 1):
            total_cost += problem.distance_matrix[solution[i]][solution[i + 1]]
        return total_cost


